'use strict';

/* Кэш выдач по каталогу компаний.
 *
 * Каталог и карта строятся из одной таблицы, читаются часто и одинаковы для
 * всех: 4500 строк, маппинг каждой, а у карты ещё геокодирование и разведение
 * точек одного города. Считать это заново на каждый заход незачем — состав
 * реестра меняется редко.
 *
 * Кэш здесь не только по времени. Голый TTL означает, что завод, поправивший
 * свой профиль, минуту видит в каталоге старую версию и решает, что правка не
 * сохранилась, — а это ровно тот сорт «сайт сломался», который мы разбираем
 * вторую неделю. Поэтому записи в companies сбрасывают кэш немедленно, а TTL
 * остаётся страховкой для того, что меняет базу мимо процесса: импорт
 * реестра, psql руками, второй инстанс.
 *
 * Важное ограничение: сюда кладутся только выдачи, одинаковые для всех.
 * Ничего, что зависит от текущего пользователя (избранное, контакты по
 * правам), в этот кэш класть нельзя — оно утечёт соседу.
 */

const entries = new Map();

function get(key, ttlMs) {
    const hit = entries.get(key);
    if (!hit) return null;
    if (Date.now() - hit.ts >= ttlMs) {
        entries.delete(key);
        return null;
    }
    return hit.data;
}

function set(key, data) {
    entries.set(key, { ts: Date.now(), data });
    return data;
}

/* Зовётся из всех путей, которые пишут в companies: правка профиля, фото,
   верификация, привязка профиля из реестра при регистрации. Дешевле сбросить
   лишний раз, чем показать вчерашний каталог. */
function invalidate() {
    entries.clear();
}

module.exports = { get, set, invalidate };
