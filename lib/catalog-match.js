'use strict';

// Сопоставление текстовых полей компании со справочниками услуг и изделий.
//
// Задача: у 4500 карточек производственные возможности записаны прозой — в
// полях specialization и products («Токарная и фрезерная обработка, валы,
// втулки»). Справочник же хранит сущности. Связи между ними нужно один раз
// вытащить из текста, иначе страницы кластера будет нечем наполнить.
//
// Главное требование здесь — точность, а не полнота. Лишняя связь ставит
// компанию на страницу, которую она не обслуживает, и ТЗ §6.4 это прямо
// запрещает: «Листинг не должен включать компании, не связанные с тематикой
// страницы». Пропущенную связь компания добавит сама при заполнении профиля,
// а выдуманную придётся вычищать руками. Поэтому все спорные случаи решаются
// в пользу отказа, а результат помечается слабейшим уровнем подтверждения
// (`registry`) и никогда не выдаёт себя за подтверждённый модератором.
//
// Почему здесь свой стеммер, а не общий с lib/producer-search: тот обрезает
// слова до шести символов и решает другую задачу — предварительный отбор
// кандидатов для модели, где важнее не потерять. «валы» и «валов» он оставляет
// разными, и для отбора это допустимо, а для связи со справочником — нет.

const { normalize } = require('./producer-search');

/* Окончания отбрасываются от самого длинного к самому короткому: иначе «ами»
   в «валами» срежется как «и», и слово не сойдётся с «валов». Ниже трёх букв
   корень не укорачиваем — «ось» не должна превратиться в «ос». */
const ENDINGS = [
    'иями', 'ями', 'ами', 'ого', 'ему', 'ыми', 'ими', 'ов', 'ев', 'ый', 'ий', 'ая', 'яя',
    'ое', 'ее', 'ые', 'ие', 'ой', 'ей', 'ом', 'ем', 'ах', 'ях', 'ам', 'ям', 'ую', 'юю',
    'ии', 'ия', 'ью', 'ья', 'у', 'ю', 'а', 'я', 'ы', 'и', 'о', 'е', 'ь',
].sort((a, b) => b.length - a.length);

const MIN_STEM = 3;

/** «валы», «валов», «валами» → «вал»; «токарная», «токарной» → «токарн». */
function stem(word) {
    for (const end of ENDINGS) {
        if (word.length - end.length >= MIN_STEM && word.endsWith(end)) {
            return word.slice(0, -end.length);
        }
    }
    return word;
}

/* Слова, которые в названии сущности ничего не отбирают. Список короче, чем в
   поиске: здесь разбирается не запрос человека, а название из справочника,
   и «изготовление» в «изготовление валов» действительно лишнее, а вот
   «обработка» в «токарная обработка» — нет. */
const NOISE = new Set([
    'и', 'или', 'для', 'под', 'из', 'на', 'в', 'во', 'с', 'со', 'по', 'к', 'от', 'до',
    'при', 'за', 'над', 'про', 'без', 'изготовлен', 'производств', 'выпуск', 'поставк',
    'услуг', 'работ', 'заказ',
]);

/* Беглая гласная: «втулка» в родительном множественного даёт «втулок», и корень
   «втулок» с «втулк» уже не сходится. Вернуть гласную на место нельзя зная
   только слово — у «станок» она беглая (станка), а у «поток» нет (потока), и
   различить их без словаря невозможно.

   Поэтому не заменяем корень, а добавляем второй вариант. Лишний вариант ничем
   не грозит: он совпадёт только с сущностью, у которой ровно такой корень, а
   выдуманное «потк» в справочнике не встретится. */
const FLEETING = /^(.*[бвгджзклмнпрстфхцчшщ])[оеё]к$/;

function fleetingVariant(word) {
    const m = FLEETING.exec(word);
    return m ? m[1] + 'к' : null;
}

/** Текст → набор корней. Порядок не важен, повторы схлопываются. */
function tokens(text) {
    const out = new Set();
    for (const word of normalize(text).split(/[^a-zа-я0-9]+/)) {
        if (!word || word.length < 3) continue;
        const s = stem(word);
        if (s.length >= MIN_STEM && !NOISE.has(s)) out.add(s);

        const alt = fleetingVariant(word);
        if (alt && alt.length >= MIN_STEM && !NOISE.has(alt)) out.add(alt);
    }
    return out;
}

/**
 * Индекс справочника: по одной записи на сущность, с корнями названия и всех
 * синонимов. Синоним — самостоятельный повод для связи: «токарка» и «точение»
 * в тексте означают ту же услугу, что «токарная обработка».
 *
 * @param {Array<{id:number,name:string,synonyms?:string[]}>} entries
 */
function buildIndex(entries) {
    const index = [];
    for (const e of entries || []) {
        const variants = [e.name, ...(Array.isArray(e.synonyms) ? e.synonyms : [])]
            .map(v => tokens(v))
            .filter(t => t.size > 0);
        if (!variants.length) continue;
        index.push({ id: e.id, name: e.name, variants });
    }
    return index;
}

/** Совпадают ли корни. Точное равенство либо приставка не короче четырёх букв:
 *  «фрезер» и «фрезерн» — одно, а «вал» и «валют» — нет, потому что общая
 *  часть «вал» слишком коротка, чтобы что-то утверждать. */
function sameStem(a, b) {
    if (a === b) return true;
    const [short, long] = a.length <= b.length ? [a, b] : [b, a];
    return short.length >= 4 && long.startsWith(short);
}

/** Все ли корни варианта есть в тексте. Требование полного совпадения —
 *  главный источник точности: «токарная обработка» не засчитается компании,
 *  у которой в профиле есть только «обработка». */
function variantMatches(variant, textTokens) {
    for (const need of variant) {
        let found = false;
        for (const have of textTokens) {
            if (sameStem(need, have)) { found = true; break; }
        }
        if (!found) return false;
    }
    return true;
}

/**
 * Какие сущности справочника упомянуты в тексте.
 *
 * @param {string} text — объединённые поля компании
 * @param {ReturnType<buildIndex>} index
 * @returns {Array<{id:number,name:string}>}
 */
function matchEntries(text, index) {
    const textTokens = tokens(text);
    if (!textTokens.size) return [];
    const hits = [];
    for (const entry of index) {
        // Односложные названия («Валы», «Оси») отдельной защиты не требуют:
        // короткий корень сравнивается только на точное равенство (см. sameStem),
        // поэтому «вал» совпадёт с «валов» и «валами», но не с «валиком» и не с
        // «вальцовкой». Запрет на такие названия отсекал бы половину справочника
        // изделий, ничего взамен не давая.
        const ok = entry.variants.some(v => variantMatches(v, textTokens));
        if (ok) hits.push({ id: entry.id, name: entry.name });
    }
    return hits;
}

module.exports = { tokens, stem, buildIndex, matchEntries, sameStem, NOISE };
