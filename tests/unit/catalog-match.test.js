'use strict';

const { test } = require('node:test');
const assert = require('node:assert/strict');
const { stem, tokens, buildIndex, matchEntries, sameStem } = require('../../lib/catalog-match');

/* Разбор текстовых полей компании против справочника. Цена ошибки
   несимметрична: пропущенную связь компания добавит сама при заполнении
   профиля, а выдуманная поставит её на страницу, которую она не обслуживает, —
   ТЗ §6.4 это прямо запрещает. Поэтому тесты давят прежде всего на ложные
   срабатывания. */

const DICT = [
    { id: 1, name: 'Токарная обработка', synonyms: ['токарка', 'точение'] },
    { id: 2, name: 'Фрезерная обработка' },
    { id: 3, name: 'Лазерная резка' },
    { id: 10, name: 'Валы' },
    { id: 11, name: 'Фланцы' },
    { id: 12, name: 'Втулки' },
];

function match(text) {
    return matchEntries(text, buildIndex(DICT)).map(m => m.name).sort();
}

// ─────────────────── Стеммер ───────────────────

test('падежи сходятся к одному корню', () => {
    assert.equal(stem('валы'), 'вал');
    assert.equal(stem('валов'), 'вал');
    assert.equal(stem('валами'), 'вал');
    assert.equal(stem('токарная'), 'токарн');
    assert.equal(stem('токарной'), 'токарн');
    assert.equal(stem('обработки'), 'обработк');
});

test('короткие слова не укорачиваются до бессмыслицы', () => {
    // «ось» не должна превратиться в «ос», иначе совпадёт с чем угодно.
    assert.equal(stem('ось'), 'ось');
    assert.equal(stem('вал'), 'вал');
});

test('короткие корни сравниваются только точно', () => {
    assert.ok(sameStem('вал', 'вал'));
    assert.ok(!sameStem('вал', 'валик'), '«валик» — не вал');
    assert.ok(!sameStem('вал', 'вальц'), '«вальцовка» — не вал');
    assert.ok(sameStem('фрезер', 'фрезерн'), 'длинный общий корень — одно и то же');
});

// ─────────────────── Совпадения ───────────────────

test('простое перечисление разбирается целиком', () => {
    assert.deepEqual(
        match('Токарная и фрезерная обработка, изготовление валов и фланцев'),
        ['Валы', 'Токарная обработка', 'Фланцы', 'Фрезерная обработка']
    );
});

test('синоним засчитывается как сама сущность', () => {
    assert.deepEqual(match('Выполняем точение и расточку'), ['Токарная обработка']);
    assert.deepEqual(match('Токарка, сварка'), ['Токарная обработка']);
});

test('нужны все слова названия, а не любое из них', () => {
    // Это главный источник точности: «обработка» без «токарной» ничего не значит,
    // иначе услуга прилипнет к каждому второму профилю.
    assert.deepEqual(match('Обработка металлов давлением'), []);
    assert.deepEqual(match('Резка бумаги'), [], 'резка без «лазерной» — не та услуга');
});

test('однокоренной мусор не превращается в связь', () => {
    assert.deepEqual(match('Производство вальцовочного оборудования'), []);
    assert.deepEqual(match('Валики малярные и кисти'), [], '«валики» — не «валы»');
});

test('падежи и множественное число не мешают', () => {
    assert.deepEqual(match('Изготовление втулок'), ['Втулки']);
    assert.deepEqual(match('Поставка фланцев по ГОСТ'), ['Фланцы']);
    assert.deepEqual(match('Работы по токарной обработке'), ['Токарная обработка']);
});

test('служебные слова не создают совпадений', () => {
    // «изготовление» и «производство» выброшены как шум: они есть почти в каждом
    // профиле и ничего не отбирают.
    assert.deepEqual(match('Изготовление и производство, поставка и услуги'), []);
});

test('пустой и мусорный текст ничего не даёт', () => {
    assert.deepEqual(match(''), []);
    assert.deepEqual(match('   ...   '), []);
    assert.deepEqual(match('ООО «Ромашка»'), []);
});

// ─────────────────── Индекс ───────────────────

test('записи без разбираемого названия в индекс не попадают', () => {
    const index = buildIndex([
        { id: 1, name: '...' },
        { id: 2, name: 'Валы' },
        { id: 3, name: '' },
    ]);
    assert.equal(index.length, 1);
    assert.equal(index[0].id, 2);
});

test('синонимы не обязательны и не ломают индекс', () => {
    const index = buildIndex([
        { id: 1, name: 'Валы' },
        { id: 2, name: 'Оси', synonyms: null },
        { id: 3, name: 'Втулки', synonyms: ['вкладыши'] },
    ]);
    assert.equal(index.length, 3);
    assert.deepEqual(
        matchEntries('Поставляем вкладыши', index).map(m => m.name),
        ['Втулки']
    );
});

test('токенизация схлопывает повторы', () => {
    const t = tokens('Валы, валов, валами');
    assert.deepEqual([...t], ['вал']);
});
