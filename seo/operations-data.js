function operationBySlug(slug) {
    return OPERATIONS.find(o => o.slug === String(slug || '').toLowerCase()) || null;
}

/** Текст профиля, по которому решаем, заявляет предприятие операцию или нет. */
function producerText(p) {
    return [
        p.specialization || '',
        p.products || '',
        p.about || '',
        Array.isArray(p.equipment) ? p.equipment.join(' ') : '',
        Array.isArray(p.capabilities) ? p.capabilities.join(' ') : '',
    ].join(' ');
}

function producerHasOperation(producer, op) {
    const text = producerText(producer);
    if (!op.match.test(text)) return false;
    if (op.exclude && op.exclude.test(text)) return false;
    return true;
}

